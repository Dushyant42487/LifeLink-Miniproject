CREATE TABLE donors (
    id TEXT PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    "passwordHash" TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'donor',
    name TEXT NOT NULL,
    phone TEXT,
    "createdAt" TEXT NOT NULL,
    "avatarUrl" TEXT,
    "bloodGroup" TEXT NOT NULL,
    dob TEXT NOT NULL,
    gender TEXT NOT NULL,
    address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    "emergencyContact" JSONB NOT NULL,
    "lastDonationDate" TEXT,
    "weightKg" NUMERIC NOT NULL,
    "isEligible" BOOLEAN NOT NULL DEFAULT true,
    "deferralReason" TEXT,
    "totalDonationsCount" INTEGER NOT NULL DEFAULT 0,
    "totalVolumeMl" INTEGER NOT NULL DEFAULT 0,
    "notificationPreferences" JSONB NOT NULL
);

CREATE TABLE hospitals (
    id TEXT PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    "passwordHash" TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'hospital',
    name TEXT NOT NULL,
    phone TEXT,
    "createdAt" TEXT NOT NULL,
    "avatarUrl" TEXT,
    "hospitalName" TEXT NOT NULL,
    "licenseId" TEXT NOT NULL,
    "verificationStatus" TEXT NOT NULL DEFAULT 'Pending Verification',
    address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    "contactPerson" TEXT NOT NULL,
    "emergencyPhone" TEXT NOT NULL,
    latitude NUMERIC NOT NULL,
    longitude NUMERIC NOT NULL
);

CREATE TABLE blood_banks (
    id TEXT PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    "passwordHash" TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'blood_bank',
    name TEXT NOT NULL,
    phone TEXT,
    "createdAt" TEXT NOT NULL,
    "avatarUrl" TEXT,
    "bloodBankName" TEXT NOT NULL,
    "registrationId" TEXT NOT NULL,
    "contactPerson" TEXT NOT NULL,
    address TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    "emergencyPhone" TEXT NOT NULL,
    latitude NUMERIC NOT NULL,
    longitude NUMERIC NOT NULL
);
